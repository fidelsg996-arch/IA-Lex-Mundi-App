export const obtenerParticipanteUnico = (torneoId, fase, evitarNombre = null) => {
  const key = `${torneoId}_${fase}`;
  if (!historialParticipantes[key]) {
    historialParticipantes[key] = [];
  }
  
  const usados = historialParticipantes[key];
  // Filtrar participantes no usados y que no sean del usuario actual
  let disponibles = participantesIA.filter(p => {
    const usado = usados.some(u => u.nombre === p.nombre);
    const evitar = evitarNombre ? (typeof evitarNombre === 'string' ? evitarNombre : evitarNombre.nombre) : null;
    return !usado && p.nombre !== evitar;
  });
  
  // Si no hay disponibles, reiniciar el historial (excepto el último usado y el actual)
  if (disponibles.length === 0) {
    const ultimoUsado = usados[usados.length - 1];
    const nombreUltimo = ultimoUsado?.nombre;
    historialParticipantes[key] = [];
    
    disponibles = participantesIA.filter(p => {
      return p.nombre !== nombreUltimo && p.nombre !== evitarNombre;
    });
    
    const seleccionado = disponibles[Math.floor(Math.random() * disponibles.length)];
    historialParticipantes[key].push(seleccionado);
    return seleccionado;
  }
  
  const seleccionado = disponibles[Math.floor(Math.random() * disponibles.length)];
  usados.push(seleccionado);
  return seleccionado;
};

